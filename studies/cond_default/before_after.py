"""CONDITIONS default 0 -> 1: before/after on every world set the project has, on one binary.

"before" = SET CONDITIONS 0, which the gate shows is output-identical to the previous engine (README.md here).
"after"  = the new default. Profiles: default, strict, tendency (built-in policies).

  python3 before_after.py run      resumable; one file per (set, world, seed) in results/
  python3 before_after.py report   writes REPORT.md
"""
import glob, json, os, statistics, sys, time

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path[:0] = [ROOT, os.path.join(ROOT, "studies/sealed"), os.path.join(ROOT, "studies/capability/tools"), os.path.join(ROOT, "studies/round2/confirm"),
                os.path.join(ROOT, "studies/evidence_policy/confirm"), os.path.join(ROOT, "studies/sealed2")]
import cworlds, metrics  # noqa: E402
from interface import EGMAdapter  # noqa: E402
RES = os.path.join(HERE, "results")
SIDES = {"before": {"CONDITIONS": 0}, "after": {}}
PROFILES = {"default": None, "strict": "strict", "tendency": "tendency"}
SEALED1 = ["inverse", "symmetric", "transitive", "composition", "path3", "conditional", "conditional_control",
           "conditional_decoy", "branching", "depth", "noise", "control", "hub", "ambiguous"]
HEAVY = {"reversed_weak"}   # Round 1 profiles flood this world (~100-600 s per run): default profile only


def items():
    out = []
    for name, *_ in cworlds.CATALOGUE:
        out += [("dev", name, s) for s in range(5)]
    import confirm as c1
    out += [("sealed1", st, s) for st in SEALED1 for s in c1.SEEDS]
    import confirm2 as c2
    out += [("sealed2", st, s) for st in c2.STRUCTURES for s in c2.SEEDS]
    import realdata, realdata2
    out += [("real1", n, s) for n in realdata.SETS for s in range(1000, 1005)]
    out += [("real2", n, s) for n in realdata2.SETS for s in realdata2.SEEDS]
    return out


def load(kind, name, seed):
    if kind == "dev":
        return cworlds.load(name, seed), {}
    if kind == "sealed1":
        import confirm as c1
        return c1.sealed_world(name, seed), {}
    if kind == "sealed2":
        import confirm2 as c2
        return c2.sealed_world(name, seed), {}
    mod = __import__("realdata" if kind == "real1" else "realdata2")
    w = mod.load(name, seed)
    return w, {"MAXWORDS": w.maxwords}


def run():
    os.makedirs(RES, exist_ok=True)
    for kind, name, seed in items():
        f = os.path.join(RES, f"{kind}__{name}__{seed}.json")
        if os.path.exists(f):
            continue
        w, extra = load(kind, name, seed); rec = {"kind": kind, "world": name, "seed": seed, "runs": {}}
        t0 = time.time()
        for side, st in SIDES.items():
            for p, pol in PROFILES.items():
                if name in HEAVY and p != "default":
                    continue
                m = metrics.measure(w, EGMAdapter({**extra, **st}, policy=pol).run(w.lines, w.rels, []))
                rec["runs"][f"{side}/{p}"] = {k: m.get(k) for k in ("precision", "recall", "new", "wrong", "aurc", "seconds", "peak_mb", "invented_unseen", "proofs_invalid")}
        json.dump(rec, open(f + ".tmp", "w")); os.replace(f + ".tmp", f)
        print(kind, name, seed, f"{time.time() - t0:.1f}s", flush=True)


def report():
    recs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(RES, "*.json")))]
    G = {}
    for r in recs:
        G.setdefault((r["kind"], r["world"]), []).append(r)
    mean = lambda xs: statistics.mean(xs) if xs else None
    def agg(rs, key, field):
        return mean([r["runs"][key][field] for r in rs if key in r["runs"] and r["runs"][key][field] is not None])
    f3 = lambda x: "–" if x is None else f"{x:.3f}"
    f0 = lambda x: "–" if x is None else f"{x:,.0f}"
    L = ["# CONDITIONS 1 as the default: before and after\n",
         "Generated by `before_after.py report` from `results/`. Before = `SET CONDITIONS 0` (output-identical to the "
         "previous engine, see README.md); after = the new default. Means over seeds or splits; precision is left out of a "
         "mean where nothing was derived (–: nothing derived in any seed).\n"]
    kinds = {"dev": "Development worlds (seeds 0-4)", "sealed1": "Round 1 sealed worlds (seeds 1000-1004)",
             "sealed2": "Round 2 sealed worlds (seeds 2000-2004)", "real1": "Real data, Round 1 sets (splits 1000-1004)",
             "real2": "Real data, Round 2 sets (splits 2000-2004)"}
    totals = {}
    for kind, title in kinds.items():
        L += [f"## {title}\n", "| world | profile | precision before → after | recall before → after | new before → after | wrong before → after | seconds before → after |",
              "|---|---|---|---|---|---|---|"]
        for (k, w), rs in G.items():
            if k != kind:
                continue
            for p in PROFILES:
                b, a = f"before/{p}", f"after/{p}"
                if b not in rs[0]["runs"]:
                    continue
                row = [agg(rs, b, "precision"), agg(rs, a, "precision"), agg(rs, b, "recall"), agg(rs, a, "recall"),
                       agg(rs, b, "new"), agg(rs, a, "new"), agg(rs, b, "wrong"), agg(rs, a, "wrong"), agg(rs, b, "seconds"), agg(rs, a, "seconds")]
                changed = any(abs((row[i] or 0) - (row[i + 1] or 0)) > 1e-9 for i in (0, 2, 4, 6))
                mark = " **changed**" if changed else ""
                L.append(f"| {w}{mark} | {p} | {f3(row[0])} → {f3(row[1])} | {f3(row[2])} → {f3(row[3])} | {f0(row[4])} → {f0(row[5])} | {f0(row[6])} → {f0(row[7])} | {row[8]:.2f} → {row[9]:.2f} |")
                t = totals.setdefault((kind, p), {"worlds": 0, "changed": 0, "wrong_b": 0, "wrong_a": 0, "new_b": 0, "new_a": 0, "sec_b": 0, "sec_a": 0, "rec_down": 0, "prec_up": 0, "prec_down": 0})
                t["worlds"] += 1; t["changed"] += changed
                t["wrong_b"] += row[6] or 0; t["wrong_a"] += row[7] or 0; t["new_b"] += row[4] or 0; t["new_a"] += row[5] or 0
                t["sec_b"] += row[8] or 0; t["sec_a"] += row[9] or 0
                if row[2] is not None and row[3] is not None and row[3] < row[2] - 1e-9: t["rec_down"] += 1
                if row[0] is not None and row[1] is not None:
                    t["prec_up"] += row[1] > row[0] + 1e-9; t["prec_down"] += row[1] < row[0] - 1e-9
        L.append("")
    S = ["## Summary\n", "| world set | profile | worlds | changed | precision up / down | recall down | wrong answers before → after | new answers before → after | seconds before → after (sum of means) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for (kind, p), t in totals.items():
        S.append(f"| {kind} | {p} | {t['worlds']} | {t['changed']} | {t['prec_up']} / {t['prec_down']} | {t['rec_down']} | {t['wrong_b']:,.0f} → {t['wrong_a']:,.0f} | {t['new_b']:,.0f} → {t['new_a']:,.0f} | {t['sec_b']:.1f} → {t['sec_a']:.1f} |")
    json.dump({f"{k}/{p}": t for (k, p), t in totals.items()}, open(os.path.join(HERE, "summary.json"), "w"), indent=1)
    open(os.path.join(HERE, "REPORT.md"), "w").write("\n".join(L[:2] + S + [""] + L[2:]) + "\n")
    print("\n".join(S))


if __name__ == "__main__":
    {"run": run, "report": report}[sys.argv[1]]()
