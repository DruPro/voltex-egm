"""Capability profile: every engine profile on every world in the catalogue, through the evaluation interface.

  python3 profile.py [--seeds N] [--only WORLD] [--out FILE]   run, then write the report
  python3 profile.py --report [--out FILE]                      only rewrite BASELINE.md from the results file

Profiles (all scored the same way, against each world's complete truth):
  egm-default        voltex2 at default settings (TENDENCYSTEPS -1)
  egm-ts0            voltex2 with TENDENCYSTEPS 0 (today's in-engine strict option)
  egm-strict-filter  voltex2 at defaults, keeping only law-tier inferences (the SDK's strict=True)
  egm-matched        voltex2 with the structure's own setting (TREES, CHAIN 3, CONDITIONS, DEPTH 0): TUNED per structure
  B0-stated, B1-majority, B2-inverse   trivial reference engines (baselines.py)
Plus C9 consistency (metamorphic transforms and determinism) on egm-default.
The engine binary comes from VOLTEX (default build/voltex2).
"""
import hashlib, json, os, random, statistics, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(STUDY, "..", ".."))
sys.path.insert(0, HERE)
from interface import EGMAdapter  # noqa: E402
import baselines, metamorphic, metrics  # noqa: E402
import cworlds as worlds  # noqa: E402

KEYS = ["precision", "recall", "new", "wrong", "aurc", "p_at_r50", "invented_unseen", "abstention", "undet_answered",
        "retention", "flag_precision", "flag_recall", "seconds", "peak_mb"]


def profiles(world):
    out = [("egm-default", EGMAdapter({})), ("egm-ts0", EGMAdapter({"TENDENCYSTEPS": 0})),
           ("egm-strict-filter", EGMAdapter({}, strict_filter=True))]
    if world.matched:
        out.append(("egm-matched", EGMAdapter(world.matched)))
    return out + [(b.name, b) for b in baselines.BASELINES]


def summary(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return None
    return {"mean": statistics.mean(xs), "sd": statistics.stdev(xs) if len(xs) > 1 else 0.0,
            "min": min(xs), "max": max(xs), "n": len(xs)}


def run_world(name, seeds):
    per = {}          # profile -> [metrics per seed]
    meta = {}         # transform -> [jaccard per seed]; "determinism" -> [bool]
    w0 = None
    for s in range(seeds):
        w = worlds.load(name, s); w0 = w0 or w
        st = sorted(worlds.stated(w)); probes = random.Random(s).sample(st, min(150, len(st)))
        base_derived = None; sets = {}
        for pname, eng in profiles(w):
            run = eng.run(w.lines, w.rels, probes)
            per.setdefault(pname, []).append(metrics.measure(w, run))
            sets[pname] = {a.fact for a in run.answers}
            if pname == "egm-default":
                base_derived = {a.fact for a in run.answers}
                base_conf = sorted((a.fact, a.confidence) for a in run.answers)
        # C-H3 baseline: answers a stricter option gives that the default lacks (a nesting violation)
        meta.setdefault("nesting_ts0", []).append(len(sets["egm-ts0"] - sets["egm-default"]))
        meta.setdefault("nesting_ts0_correct", []).append(len((sets["egm-ts0"] - sets["egm-default"]) & w.truth))
        d = EGMAdapter({})
        again = d.run(w.lines, w.rels, [])
        meta.setdefault("determinism", []).append(sorted((a.fact, a.confidence) for a in again.answers) == base_conf)
        for tname, tf in metamorphic.TRANSFORMS.items():
            lines2, back = tf(w.lines, w.rels, 1000 + s)
            r2 = d.run(lines2, w.rels, [])
            mapped = {m for m in (back(a.fact) for a in r2.answers) if m and None not in m}
            meta.setdefault(tname, []).append(metamorphic.compare(base_derived, mapped))
        print(f"  {name} seed {s} done", flush=True)
    return {"world": name, "structure": w0.structure, "matched": w0.matched, "seeds": seeds,
            "profiles": {p: {"summary": {k: summary([m.get(k) for m in ms]) for k in KEYS}, "per_seed": ms}
                         for p, ms in per.items()},
            "consistency": {k: (summary([float(x) for x in v]) if k != "determinism" else {"all": all(v), "n": len(v)})
                            for k, v in meta.items()}}


def fmt(S, k, digits=3):
    x = S.get(k)
    if x is None:
        return "undef."
    if x["n"] == 1 or x["sd"] == 0:
        return f"{x['mean']:.{digits}f}"
    return f"{x['mean']:.{digits}f} ± {x['sd']:.{digits}f}"


def cnt(S, k):
    x = S.get(k)
    return "undef." if x is None else f"{x['mean']:.0f}"


def report(data, path):
    m = data["meta"]; L = []
    L.append("# Capability profile: baseline (G3)\n")
    L.append(f"Generated by `studies/capability/tools/profile.py`; do not edit by hand. Engine binary sha256 "
             f"`{m['binary_sha256'][:16]}…`, tool commit `{m['tool_commit']}`, {m['seeds']} seeds per world, "
             f"{m['date']}.\n")
    L.append("Scored through the evaluation interface (`tools/interface.py`) against each world's complete truth. "
             "Values are mean ± sd over seeds. \"undef.\" = nothing to divide by (no new facts, nothing missing, no "
             "undeterminable queries labelled, no corruptions). AURC = mean risk (1 − precision) over the engine's own "
             "ranking of its new answers: lower is better, read it with `new` beside it. P@R50 = precision when the "
             "ranking first reaches 50% recall. `egm-matched` is tuned per structure and is labelled so. Trivial "
             "baselines are given the relation phrases, which EGM must discover.\n")
    L.append("## Worst structure, per profile\n")
    L.append("The decision rules judge a change on its worst structure as well as its mean. Control world excluded "
             "from the precision and recall columns; its own column counts false discoveries.\n")
    L.append("| Profile | Worst precision (world) | Worst recall (world) | Invented, all worlds | False discoveries on control |")
    L.append("|---|---|---|---|---|")
    names = [w for w in data["worlds"]]
    allp = []
    for w in names:
        for p in w["profiles"]:
            if p not in allp:
                allp.append(p)
    for p in allp:
        wp, wr, inv, ctrl = None, None, 0.0, "–"
        for w in names:
            if p not in w["profiles"]:
                continue
            S = w["profiles"][p]["summary"]
            if w["world"] == "random_links":
                ctrl = cnt(S, "new"); continue
            if S["precision"] and (wp is None or S["precision"]["mean"] < wp[0]):
                wp = (S["precision"]["mean"], w["world"])
            if S["recall"] and (wr is None or S["recall"]["mean"] < wr[0]):
                wr = (S["recall"]["mean"], w["world"])
            if S["invented_unseen"]:
                inv += S["invented_unseen"]["mean"]
        f = lambda t: "undef." if t is None else f"{t[0]:.3f} ({t[1]})"
        L.append(f"| {p} | {f(wp)} | {f(wr)} | {inv:.0f} | {ctrl} |")
    L.append("")
    L.append("## Per world\n")
    for w in names:
        L.append(f"### {w['world']}: {w['structure']}\n")
        if w["matched"]:
            L.append(f"`egm-matched` = {', '.join(f'{k} {v}' for k, v in w['matched'].items())}.\n")
        L.append("| Profile | Precision | Recall | New | Wrong | AURC | P@R50 | Invented | Abstention (undet. answered) | Retention | Flag P / R | s | MB |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for p, v in w["profiles"].items():
            S = v["summary"]
            ab = "not labelled" if S["abstention"] is None and S["undet_answered"] is None else f"{fmt(S, 'abstention')} ({cnt(S, 'undet_answered')})"
            fl = "–" if S["flag_recall"] is None else f"{fmt(S, 'flag_precision', 2)} / {fmt(S, 'flag_recall', 2)}"
            L.append(f"| {p} | {fmt(S, 'precision')} | {fmt(S, 'recall')} | {cnt(S, 'new')} | {cnt(S, 'wrong')} | "
                     f"{fmt(S, 'aurc')} | {fmt(S, 'p_at_r50')} | {cnt(S, 'invented_unseen')} | {ab} | {fmt(S, 'retention')} | "
                     f"{fl} | {fmt(S, 'seconds', 2)} | {fmt(S, 'peak_mb', 0)} |")
        L.append("")
    L.append("## C9 consistency (egm-default)\n")
    L.append("Jaccard similarity of the derived facts after each transform, mapped back, against the untransformed run "
             "(1.000 = identical). Mean, with the lowest seed in brackets. Determinism = the same input twice gives the "
             "same answers and confidences.\n")
    L.append("| World | Rename | Shuffle | Duplicate | Distract | Determinism |")
    L.append("|---|---|---|---|---|---|")
    for w in names:
        c = w["consistency"]
        g = lambda k: f"{c[k]['mean']:.3f} [{c[k]['min']:.3f}]" if c.get(k) else "–"
        d = c.get("determinism", {})
        L.append(f"| {w['world']} | {g('rename')} | {g('shuffle')} | {g('duplicate')} | {g('distract')} | "
                 f"{'yes' if d.get('all') else 'NO'} ({d.get('n', 0)} runs) |")
    L.append("")
    L.append("## C-H3 baseline: is today's strict option nested in the default?\n")
    L.append("Answers `egm-ts0` (`TENDENCYSTEPS 0`) gives that `egm-default` does not, per seed (mean, max), and how many "
             "of them are true. Non-zero means the two options are not ordered: dropping tendency rules changes which "
             "value wins a vote, not only which answers are shown. The SDK's strict filter is nested by construction.\n")
    L.append("| World | Violations, mean (max) | Of which true, mean |")
    L.append("|---|---|---|")
    for w in names:
        c = w["consistency"]; v = c.get("nesting_ts0"); t = c.get("nesting_ts0_correct")
        if v:
            L.append(f"| {w['world']} | {v['mean']:.1f} ({v['max']:.0f}) | {t['mean']:.1f} |")
    L.append("")
    L.append("## Not measured in this baseline\n")
    L.append("- **C2 structural discovery** (behavioural rule recovery per generator rule): needs per-rule labels in the generators.\n"
             "- **C3 by proof depth**: needs depth labels; reported here per structure only.\n"
             "- **C6** is covered only by the three `hidden` coverage levels (no recall-vs-observed curve yet).\n"
             "- **C8 generalization** (renamed vocabulary is in C9; held-out depth and unseen combinations are not).\n"
             "- **C10 explanation fidelity** (independent proof checker, counterfactual test).\n"
             "- **C11 change** and **C13 active verification** (the verification world of Investigation V).\n"
             "- **Undeterminable queries** are labelled for `remainders` only; `lineage`, `gates`, `harvest` have none by "
             "construction; `company` and `hidden` are not labelled.\n")
    open(path, "w").write("\n".join(L) + "\n")
    print("wrote", os.path.relpath(path, ROOT))


def main():
    a = sys.argv[1:]
    out = a[a.index("--out") + 1] if "--out" in a else os.path.join(STUDY, "baseline", "profile.json")
    md = os.path.join(STUDY, "BASELINE.md")
    if "--report" in a:
        report(json.load(open(out)), md); return
    seeds = int(a[a.index("--seeds") + 1]) if "--seeds" in a else 5
    only = a[a.index("--only") + 1] if "--only" in a else ""
    binary = os.environ.get("VOLTEX", os.path.join(ROOT, "build", "voltex2"))
    res = []
    for nm, *_ in worlds.CATALOGUE:
        if only and only != nm:
            continue
        t = time.time(); res.append(run_world(nm, seeds)); print(f"{nm}: {time.time() - t:.1f} s", flush=True)
    meta = {"binary_sha256": hashlib.sha256(open(binary, "rb").read()).hexdigest(),
            "tool_commit": subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip(),
            "seeds": seeds, "date": time.strftime("%Y-%m-%d")}
    os.makedirs(os.path.dirname(out), exist_ok=True)
    json.dump({"meta": meta, "worlds": res}, open(out, "w"), indent=1)
    print("wrote", os.path.relpath(out, ROOT))
    if not only:
        report({"meta": meta, "worlds": res}, md)


if __name__ == "__main__":
    main()
