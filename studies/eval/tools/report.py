"""Write ../BASELINE.md from the files in ../baseline and ../validation (every number recomputed here).

  python3 report.py
"""
import json, os, statistics, sys
HERE = os.path.dirname(os.path.abspath(__file__)); STUDY = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(STUDY, "..", "..")); V = os.path.join(STUDY, "validation")
STRESS = os.path.join(ROOT, "studies", "stress", "runs")


def fmt(s, k, d=3):
    x = s.get(k)
    if x is None: return "undefined"
    return f"{x['mean']:.{d}f} ± {x['sd']:.{d}f} [{x['min']:.{d}f}, {x['max']:.{d}f}]"


def jsonl(p): return {json.loads(l)["cell"]: json.loads(l) for l in open(p) if l.strip()}


def main():
    sc = json.load(open(os.path.join(STUDY, "baseline", "scorecard.json")))
    rep = json.load(open(os.path.join(STUDY, "baseline", "scorecard_repeat.json")))
    strip = lambda c: [{k: v for k, v in r.items() if k != "seconds"} for r in c["per_seed"]]
    det_same = sum(strip(a) == strip(b) for a, b in zip(sc["cells"], rep["cells"]))
    rows = []
    for c in sc["cells"]:
        S = c["summary"]
        rows.append(f"| {c['capability']} | `{c['cell']}` | {fmt(S, 'precision')} | {fmt(S, 'recall')} | "
                    f"{S['derived_new']['mean']:.0f} | {fmt(S, 'law_precision')} ({S['law_new']['mean']:.0f}) | "
                    f"{fmt(S, 'tendency_precision')} ({S['tendency_new']['mean']:.0f}) | {S['seconds']['mean']:.2f} |")
    g_self = json.load(open(os.path.join(V, "gate_self.json"))); g_old = json.load(open(os.path.join(V, "gate_vs_ac54dd9.json")))
    sens = open(os.path.join(V, "gate_sensitivity.txt")).read().strip().splitlines()[-1]
    # hashes: the recorded C1 run, with the settings cells from its hash rerun c1_s (stress DEVIATIONS 1). Timings: the
    # timed run c1 only; c1_s ran side by side with base_s, so its timings are not comparable (checked below).
    timed = jsonl(os.path.join(STRESS, "c1.jsonl")); reruns = jsonl(os.path.join(STRESS, "c1_s.jsonl"))
    ref = dict(timed); ref.update(reruns)
    cur = jsonl(os.path.join(V, "bench_main.jsonl"))
    same = diff = nc = 0; ratios = []; diffs = []; rr = []
    for c in sorted(set(ref) & set(cur)):
        x, y = ref[c], cur[c]
        if x["status"] or y["status"]: nc += 1; continue
        if x["hash"] == y["hash"]: same += 1
        else: diff += 1; diffs.append(c)
        if x["s"] >= 1.0: (rr if c in reruns else ratios).append(y["s"] / x["s"])
    md = f"""# Baseline and validation

Generated by `studies/eval/tools/report.py`; do not edit by hand. Engine binary sha256 `{sc['meta']['binary_sha256'][:16]}…`,
tool commit `{sc['meta']['tool_commit']}`.

## Scorecard (`tools/scorecard.py`, {sc['meta']['seeds']} seeds per cell)

Values are mean ± sd [min, max] over seeds. "Undefined" means there was nothing to divide by: no new facts, or
nothing missing. Tier columns give precision with the mean count of new facts in that tier in brackets.

| Capability | Cell | Precision | Recall | New facts | Law-tier precision (n) | Tendency-tier precision (n) | s |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

**Determinism:** a second full run gave identical per-seed results in {det_same} of {len(sc['cells'])} cells (timings
excluded).

## Validation of the existing tools on this commit

| Check | Result |
|---|---|
| Gate, current build vs itself | {g_self['identical']} / {g_self['cells']} cells identical |
| Gate sensitivity: one side with `RATE 0.3` | {sens} (the gate detects a behaviour change) |
| Gate, current build vs a rebuild of `ac54dd9` (before `CLUSTERSTREAM` and C1) | {g_old['identical']} / {g_old['cells']} cells identical |
| Stress bench, current build vs the recorded C1 run | {same} identical, {diff} different, {nc} not comparable (a timeout or memory cap on either side) |
| Stress bench timing, current / recorded timed run (cells ≥ 1 s, n = {len(ratios)}) | median {statistics.median(ratios):.2f}, range {min(ratios):.2f}-{max(ratios):.2f} |
| Same, against the hash reruns that ran two at a time (n = {len(rr)}) | median {statistics.median(rr):.2f}, range {min(rr):.2f}-{max(rr):.2f}: not comparable |

The timing rows show run-to-run noise on one machine with an unchanged engine. A cost claim needs an effect larger
than the first range, measured on runs that don't share the machine; the second row shows what sharing it does. Stored hashes are comparable only under the same tool version. The gate's normalisation changed
in `bcb6b42`, so equivalence was checked by re-running both binaries, not against hashes stored by older runs.
{"Cells that differ: " + ", ".join(diffs) if diffs else ""}
"""
    open(os.path.join(STUDY, "BASELINE.md"), "w").write(md); print(md[:1500])


if __name__ == "__main__":
    main()
