"""Strict as shipped vs strict excluding assumed reliability bases, on every world set (development data only).
  python3 measure.py run | report"""
import dataclasses, glob, json, os, statistics, sys, time
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path[:0] = [os.path.join(ROOT, "studies/cond_default")]
import before_after as ba  # world catalogue and loaders (dev, sealed1, sealed2, real1, real2)
import metrics
from interface import EGMAdapter
from egm.policy import BUILTINS
S = BUILTINS["strict"]
def variant(name, bases):
    return dataclasses.replace(S, name=name, version="1", builtin=False, thresholds=dict(S.thresholds, reliabilityBasis=list(bases)))
PROFILES = {"strict": "strict",
            "strict-no-self": variant("strict-no-self", ["agreement", "inverse", "global", "rate"]),
            "strict-measured": variant("strict-measured", ["agreement", "inverse", "rate"])}
RES = os.path.join(HERE, "results")
def run():
    os.makedirs(RES, exist_ok=True)
    only = os.environ.get("KINDS")
    for kind, name, seed in ba.items():
        if only and kind not in only.split(","): continue
        f = os.path.join(RES, f"{kind}__{name}__{seed}.json")
        if os.path.exists(f): continue
        w, extra = ba.load(kind, name, seed); rec = {"kind": kind, "world": name, "seed": seed, "runs": {}}; t = time.time()
        for cs in (0, 1):
            for p, pol in PROFILES.items():
                m = metrics.measure(w, EGMAdapter({**extra, "COVSOURCE": cs}, policy=pol).run(w.lines, w.rels, []))
                rec["runs"][f"cs{cs}/{p}"] = {k: m.get(k) for k in ("precision", "recall", "new", "wrong", "seconds")}
        json.dump(rec, open(f, "w")); print(kind, name, seed, f"{time.time() - t:.1f}s", flush=True)
def report():
    recs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(RES, "*.json")))]
    G = {}
    for r in recs: G.setdefault((r["kind"], r["world"]), []).append(r)
    mean = lambda xs: statistics.mean(xs) if xs else None
    a = lambda rs, k, f: mean([r["runs"][k][f] for r in rs if r["runs"][k][f] is not None])
    f3 = lambda x: "–" if x is None else f"{x:.3f}"
    L = ["# Strict with and without assumed reliability bases\n", "Generated by `measure.py report`. Means over seeds or splits; – = nothing derived.\n"]
    tot = {}
    for cs in (0, 1):
        L += [f"## COVSOURCE {cs}: worlds where the variants differ\n", "| set | world | strict P / R / wrong | no-self P / R / wrong | measured P / R / wrong |", "|---|---|---|---|---|"]
        for (k, w), rs in G.items():
            cells = []
            for p in PROFILES:
                key = f"cs{cs}/{p}"; cells.append((a(rs, key, "precision"), a(rs, key, "recall"), a(rs, key, "wrong")))
                t = tot.setdefault((cs, p), [0.0, 0.0, 0]); t[0] += a(rs, key, "wrong") or 0; t[1] += a(rs, key, "new") or 0
                t[2] += 1 if (a(rs, key, "recall") or 0) > 0 else 0
            if len({(round(c[1] or 0, 4), round(c[2] or 0, 1)) for c in cells}) > 1:
                L.append(f"| {k} | {w} | " + " | ".join(f"{f3(c[0])} / {f3(c[1])} / {c[2] or 0:,.0f}" for c in cells) + " |")
        L.append("")
    L += ["## Totals (sum of per-world means, all sets)\n", "| COVSOURCE | profile | wrong answers | new answers | worlds with recall > 0 |", "|---|---|---|---|---|"]
    for (cs, p), t in tot.items(): L.append(f"| {cs} | {p} | {t[0]:,.0f} | {t[1]:,.0f} | {t[2]} |")
    open(os.path.join(HERE, "REPORT.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L))
if __name__ == "__main__":
    {"run": run, "report": report}[sys.argv[1]]()
